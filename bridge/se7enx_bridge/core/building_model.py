"""Building model: Site → Building → Floor → Room, with Zones grouping rooms of one building.

Relationships follow Brick Schema concepts (Floor *hasPart* Room, Zone *hasPart* Room, equipment
*hasLocation* Room): a device references at most one room (``metadata.roomId``); floors, buildings
and sites are derived from it. Stored in ``config.json`` (no secrets). IDs are generated by the hub.
"""

from __future__ import annotations

import re
from typing import Annotated, Literal
from zoneinfo import ZoneInfo, ZoneInfoNotFoundError

from pydantic import AfterValidator, BaseModel, ConfigDict, Field
from pydantic.alias_generators import to_camel

_CONTROL = re.compile(r"[\x00-\x1f\x7f]")
PREFIX = {"site": "site", "building": "bldg", "floor": "floor", "room": "room", "zone": "zone"}
ENTITY_ID_PATTERN = r"^(site|bldg|floor|room|zone)-[0-9a-f]{8}$"
ROOM_ID_PATTERN = r"^room-[0-9a-f]{8}$"


class CoreModel(BaseModel):
    model_config = ConfigDict(extra="forbid", alias_generator=to_camel, populate_by_name=True)


def _name(value: str) -> str:
    v = value.strip()
    if not v or _CONTROL.search(v):
        raise ValueError("must be 1 to 64 printable characters")
    return v


def _timezone(value: str | None) -> str | None:
    if value is None:
        return None
    try:
        ZoneInfo(value)
    except (ZoneInfoNotFoundError, ValueError) as err:
        raise ValueError("must be an IANA time zone such as Africa/Algiers") from err
    return value


Name = Annotated[str, Field(min_length=1, max_length=64), AfterValidator(_name)]
TimeZone = Annotated[str | None, Field(default=None, max_length=64), AfterValidator(_timezone)]
BuildingKind = Literal["residential", "commercial", "industrial", "public", "other"]
RoomKind = Literal[
    "living",
    "kitchen",
    "dining",
    "bedroom",
    "bathroom",
    "office",
    "meeting",
    "corridor",
    "entrance",
    "storage",
    "technical",
    "garage",
    "outdoor",
    "other",
]
ZoneKind = Literal["lighting", "hvac", "security", "energy", "custom"]


class Site(CoreModel):
    id: str = Field(pattern=r"^site-[0-9a-f]{8}$")
    name: Name
    timezone: TimeZone = None
    address: str | None = Field(default=None, max_length=200)


class Building(CoreModel):
    id: str = Field(pattern=r"^bldg-[0-9a-f]{8}$")
    site_id: str = Field(pattern=r"^site-[0-9a-f]{8}$")
    name: Name
    kind: BuildingKind = "residential"


class Floor(CoreModel):
    id: str = Field(pattern=r"^floor-[0-9a-f]{8}$")
    building_id: str = Field(pattern=r"^bldg-[0-9a-f]{8}$")
    name: Name
    level: int = Field(default=0, ge=-20, le=300)


class Room(CoreModel):
    id: str = Field(pattern=ROOM_ID_PATTERN)
    floor_id: str = Field(pattern=r"^floor-[0-9a-f]{8}$")
    name: Name
    kind: RoomKind = "other"
    # Alternative names for voice and chat ("lounge" for "Living room", "الصالون", ...)
    aliases: list[Name] = Field(default_factory=list, max_length=8)


class Zone(CoreModel):
    id: str = Field(pattern=r"^zone-[0-9a-f]{8}$")
    building_id: str = Field(pattern=r"^bldg-[0-9a-f]{8}$")
    name: Name
    kind: ZoneKind = "custom"
    room_ids: list[str] = Field(default_factory=list, max_length=500)


class BuildingModel(CoreModel):
    sites: list[Site] = Field(default_factory=list, max_length=50)
    buildings: list[Building] = Field(default_factory=list, max_length=200)
    floors: list[Floor] = Field(default_factory=list, max_length=2000)
    rooms: list[Room] = Field(default_factory=list, max_length=10000)
    zones: list[Zone] = Field(default_factory=list, max_length=2000)


# ----------------------------------------------------------------------------- request bodies


class SiteInput(CoreModel):
    name: Name
    timezone: TimeZone = None
    address: str | None = Field(default=None, max_length=200)


class SitePatch(CoreModel):
    name: Name | None = None
    timezone: TimeZone = None
    address: str | None = Field(default=None, max_length=200)


class BuildingInput(CoreModel):
    site_id: str = Field(pattern=r"^site-[0-9a-f]{8}$")
    name: Name
    kind: BuildingKind = "residential"


class BuildingPatch(CoreModel):
    name: Name | None = None
    kind: BuildingKind | None = None


class FloorInput(CoreModel):
    building_id: str = Field(pattern=r"^bldg-[0-9a-f]{8}$")
    name: Name
    level: int = Field(default=0, ge=-20, le=300)


class FloorPatch(CoreModel):
    name: Name | None = None
    level: int | None = Field(default=None, ge=-20, le=300)


class RoomInput(CoreModel):
    floor_id: str = Field(pattern=r"^floor-[0-9a-f]{8}$")
    name: Name
    kind: RoomKind = "other"
    aliases: list[Name] = Field(default_factory=list, max_length=8)


class RoomPatch(CoreModel):
    name: Name | None = None
    kind: RoomKind | None = None
    aliases: list[Name] | None = Field(default=None, max_length=8)
    floor_id: str | None = Field(default=None, pattern=r"^floor-[0-9a-f]{8}$")


class ZoneInput(CoreModel):
    building_id: str = Field(pattern=r"^bldg-[0-9a-f]{8}$")
    name: Name
    kind: ZoneKind = "custom"
    room_ids: list[str] = Field(default_factory=list, max_length=500)


class ZonePatch(CoreModel):
    name: Name | None = None
    kind: ZoneKind | None = None
    room_ids: list[str] | None = Field(default=None, max_length=500)


class RoomTree(CoreModel):
    name: Name
    kind: RoomKind = "other"
    aliases: list[Name] = Field(default_factory=list, max_length=8)


class FloorTree(CoreModel):
    name: Name
    level: int = Field(default=0, ge=-20, le=300)
    rooms: list[RoomTree] = Field(default_factory=list, max_length=200)


class BuildingTree(CoreModel):
    name: Name
    kind: BuildingKind = "residential"
    floors: list[FloorTree] = Field(default_factory=list, max_length=100)


class SiteTree(CoreModel):
    # Either an existing site (id) to add buildings to, or a new site (name).
    id: str | None = Field(default=None, pattern=r"^site-[0-9a-f]{8}$")
    name: Name | None = None
    timezone: TimeZone = None
    address: str | None = Field(default=None, max_length=200)
    buildings: list[BuildingTree] = Field(default_factory=list, max_length=50)


class BuildingImport(CoreModel):
    sites: list[SiteTree] = Field(min_length=1, max_length=20)
